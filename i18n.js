let LANG = 'en';
try { LANG = localStorage.getItem('lang') || ((navigator.language || '').toLowerCase().startsWith('ar') ? 'ar' : 'en'); } catch (_) {}

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}

function applyI18n() {
  const root = document.documentElement;
  root.lang = LANG;
  root.dir = LANG === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach((n) => { n.placeholder = t(n.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-aria]').forEach((n) => { n.setAttribute('aria-label', t(n.dataset.i18nAria)); });
  if (document.body && document.body.dataset.title) document.title = t(document.body.dataset.title);
}

function setLang(l) {
  LANG = l;
  try { localStorage.setItem('lang', l); } catch (_) {}
  applyI18n();
  document.dispatchEvent(new Event('langchange'));
}

applyI18n();
const _langBtn = document.getElementById('langBtn');
if (_langBtn) _langBtn.addEventListener('click', () => setLang(LANG === 'ar' ? 'en' : 'ar'));
